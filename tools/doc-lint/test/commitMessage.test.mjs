/**
 * Tests for the commit-message checker used by the commit-msg hook.
 *
 * Spec: DOC-011
 */
import { describe, it, expect } from 'vitest';
import { checkCommitMessage } from '../checkCommitMessage.mjs';

const IDS = new Set(['TST-001', 'TST-002']);
const TRAILERS = 'Co-Authored-By: Someone <someone@example.org>\nClaude-Session: https://example.org/s/1';

describe('[DOC-011] commit messages', () => {
  it('[DOC-011] accepts a feature commit with a Refs footer and trailers', () => {
    const msg = `feat(server): add the pseudonym service\n\nDerives learner keys.\n\nRefs: TST-001, TST-002\n${TRAILERS}\n`;
    expect(checkCommitMessage(msg, IDS)).toEqual([]);
  });

  it('[DOC-011] accepts chores and docs without a Refs footer', () => {
    expect(checkCommitMessage('chore: bump lockfile', IDS)).toEqual([]);
    expect(checkCommitMessage('docs(specs)!: rename a section', IDS)).toEqual([]);
  });

  it('[DOC-011] accepts merge and revert commits generated by git', () => {
    expect(checkCommitMessage("Merge branch 'main' into feature", IDS)).toEqual([]);
    expect(checkCommitMessage('Revert "feat: add x"', IDS)).toEqual([]);
  });

  it('[DOC-011] ignores comment lines that git adds to the editor template', () => {
    expect(
      checkCommitMessage('# Please enter the commit message\nfix: handle empty input\nRefs: TST-001', IDS),
    ).toEqual([]);
  });

  it('[DOC-011] rejects a header that is not a Conventional Commit', () => {
    expect(checkCommitMessage('Added stuff', IDS)).toHaveLength(1);
    expect(checkCommitMessage('feature: add stuff', IDS)).toHaveLength(1);
    expect(checkCommitMessage(`chore: ${'x'.repeat(100)}`, IDS)).toContain(
      'header is 107 characters; the limit is 100',
    );
  });

  it('[DOC-011] limits the whole header, type and scope included, to 100 characters', () => {
    expect(checkCommitMessage(`chore(server): ${'x'.repeat(85)}`, IDS)).toEqual([]);
    expect(checkCommitMessage(`chore(server): ${'x'.repeat(86)}`, IDS)).toContain(
      'header is 101 characters; the limit is 100',
    );
  });

  it('[DOC-011] requires a Refs footer on feat and fix', () => {
    expect(checkCommitMessage('fix: handle empty input', IDS)).toEqual([
      'feat and fix commits need a "Refs:" footer',
    ]);
  });

  it('[DOC-011] rejects Refs that name unknown requirements', () => {
    expect(checkCommitMessage('feat: x\n\nRefs: TST-001, TST-999', IDS)).toEqual([
      'Refs: names unknown requirement TST-999',
    ]);
  });
});
